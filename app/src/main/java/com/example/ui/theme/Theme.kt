object ThemePreferences {
    private const val PREFS_NAME = "nidanmitra_theme_prefs"
    private const val KEY_DARK_MODE = "dark_mode_override"

    /**
     * Returns saved user override (`true` = Dark, `false` = Light), or `null` if following system default.
     */
    fun loadOverride(context: Context): Boolean? {
        val prefs = context.getSharedPreferences(PREFS_NAME, Context.MODE_PRIVATE)
        return if (prefs.contains(KEY_DARK_MODE)) {
            prefs.getBoolean(KEY_DARK_MODE, false)
        } else {
            null
        }
    }

    fun saveOverride(context: Context, darkMode: Boolean) {
        val prefs = context.getSharedPreferences(PREFS_NAME, Context.MODE_PRIVATE)
        prefs.edit().putBoolean(KEY_DARK_MODE, darkMode).apply()
    }
}

